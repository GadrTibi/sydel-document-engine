def selarl_blocks() -> tuple[FormBlock, ...]:
    return SELARL_BLOCKS


def selarl_fields() -> tuple[FormField, ...]:
    return SELARL_FIELDS


def selarl_fields_by_block() -> dict[str, tuple[FormField, ...]]:
    fields_by_block: dict[str, list[FormField]] = {block.key: [] for block in SELARL_BLOCKS}
    for field in SELARL_FIELDS:
        fields_by_block[field.block_key].append(field)
    return {key: tuple(fields) for key, fields in fields_by_block.items()}


def selarl_reuse_rules() -> tuple[ReuseRule, ...]:
    return SELARL_REUSE_RULES


def selarl_document_specs() -> tuple[SelarlDocumentSpec, ...]:
    return SELARL_DOCUMENTS


def selarl_required_conditions() -> tuple[str, ...]:
    return SELARL_REQUIRED_CONDITIONS


def selarl_expected_documents(
    conditions: Mapping[str, object] | None = None,
) -> tuple[ExpectedDocument, ...]:
    return tuple(
        get_expected_documents(
            {"case_type": CaseType.SELARL, "conditions": dict(conditions or {})}
        )
    )


def selarl_generable_document_codes(
    conditions: Mapping[str, object] | None = None,
) -> tuple[str, ...]:
    return tuple(
        document.document_code
        for document in selarl_expected_documents(conditions)
        if document.availability == DocumentAvailability.GENERATABLE
        and document.document_code is not None
    )


def all_selarl_v2_variables() -> tuple[str, ...]:
    return tuple(
        sorted(
            {
                variable
                for variables in SELARL_V2_VARIABLES_BY_DOCUMENT.values()
                for variable in variables
            }
        )
    )


def selarl_variable_coverage() -> tuple[VariableCoverage, ...]:
    field_index = _field_variable_index()
    reuse_index = _reuse_variable_index()
    coverage: list[VariableCoverage] = []
    for variable in all_selarl_v2_variables():
        if variable in field_index:
            coverage.append(
                VariableCoverage(
                    variable,
                    VariableCoverageStatus.UI_FIELD,
                    field_key=field_index[variable],
                )
            )
        elif variable in reuse_index:
            coverage.append(
                VariableCoverage(
                    variable,
                    VariableCoverageStatus.REUSE_RULE,
                    reuse_rule_key=reuse_index[variable],
                )
            )
        else:
            coverage.append(
                VariableCoverage(
                    variable,
                    VariableCoverageStatus.TO_ARBITRATE,
                    note=(
                        "Variable V2 conservee dans la couverture ; champ UI "
                        "detaille a arbitrer avant generation document par document."
                    ),
                )
            )
    return tuple(coverage)


def validate_selarl_schema() -> tuple[str, ...]:
    issues: list[str] = []
    block_keys = {block.key for block in SELARL_BLOCKS}
    required_blocks = {
        "qualification",
        "societe",
        "siege_social",
        "professionnel_gerant",
        "ordre_professionnel",
        "associes",
        "mandataire_signataire",
        "regime_conjoint",
        "cession_cabinet",
        "bail",
        "scm",
        "banque_financement",
        "signature",
    }
    missing_blocks = sorted(required_blocks - block_keys)
    if missing_blocks:
        issues.append(f"Blocs SELARL manquants: {', '.join(missing_blocks)}")

    for field in SELARL_FIELDS:
        if field.block_key not in block_keys:
            issues.append(f"Champ {field.key} rattache a un bloc inconnu.")
        label = field.label.casefold().strip()
        if label == "adresse":
            issues.append(f"Champ {field.key} a un label adresse non qualifie.")
        if label in {"numero", "numéro", "voie", "ville", "code postal"}:
            issues.append(f"Champ {field.key} a un label d'adresse ambigu.")

    for document in SELARL_DOCUMENTS:
        if document.block_key not in block_keys:
            issues.append(f"Document {document.document_key} rattache a un bloc inconnu.")
    for code in ("DOC-013", "DOC-014"):
        document = next(
            item for item in SELARL_DOCUMENTS if item.document_code == code
        )
        if document.expected_availability == DocumentAvailability.GENERATABLE:
            issues.append(f"{code} ne doit pas etre generable dans le pilote SELARL.")

    coverage_variables = {item.variable for item in selarl_variable_coverage()}
    missing_coverage = sorted(set(all_selarl_v2_variables()) - coverage_variables)
    if missing_coverage:
        issues.append(f"Variables V2 sans couverture: {', '.join(missing_coverage)}")
    return tuple(issues)


def _field_variable_index() -> dict[str, str]:
    v2_variables = set(all_selarl_v2_variables())
    index: dict[str, str] = {}
    for field in SELARL_FIELDS:
        for variable in field.variables:
            if variable in v2_variables:
                index.setdefault(variable, field.key)
    return index


def _reuse_variable_index() -> dict[str, str]:
    v2_variables = set(all_selarl_v2_variables())
    index: dict[str, str] = {}
    for rule_key, variables in REUSE_RULE_VARIABLES.items():
        for variable in variables:
            if variable in v2_variables:
                index.setdefault(variable, rule_key)
    return index
