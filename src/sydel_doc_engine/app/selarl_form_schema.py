class FieldRequirement(StrEnum):
    REQUIRED = "required"
    OPTIONAL = "optional"
    CONDITIONAL = "conditional"


class VariableCoverageStatus(StrEnum):
    UI_FIELD = "ui_field"
    REUSE_RULE = "reuse_rule"
    OUT_OF_SCOPE = "out_of_scope"
    TO_ARBITRATE = "to_arbitrate"


@dataclass(frozen=True)
class FormBlock:
    key: str
    label: str
    description: str


@dataclass(frozen=True)
class FormField:
    key: str
    label: str
    block_key: str
    variables: tuple[str, ...]
    requirement: FieldRequirement
    display_condition: str | None
    help_text: str
    example: str | None = None


@dataclass(frozen=True)
class ReuseRule:
    key: str
    label: str
    source: str
    target: str
    effect: str
    fields: tuple[str, ...]
    activation_condition: str


@dataclass(frozen=True)
class SelarlDocumentSpec:
    document_key: str
    document_label: str
    document_code: str | None
    block_key: str
    expected_availability: DocumentAvailability
    display_condition: str | None
    required_variables: tuple[str, ...]
    reserve_note: str | None = None


@dataclass(frozen=True)
class VariableCoverage:
    variable: str
    status: VariableCoverageStatus
    field_key: str | None = None
    reuse_rule_key: str | None = None
    note: str | None = None


